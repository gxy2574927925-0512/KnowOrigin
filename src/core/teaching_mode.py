def _is_meta(text: str, low: str) -> bool:
    """闲聊/元问题：既不推动阶梯，也不该被套上引导流程与自测题。"""
    if any(mark in text or mark in low for mark in _ASKING_MARKS):
        return False
    if len(text) > 20:
        return False
    return any(mark in text or mark in low for mark in _META_MARKS)


def _help_seeking(text: str, low: str) -> str:
    """工具性 vs 执行性求助。

    "别给答案"优先于"给我答案"判定：中文里这两种说法经常同时出现，
    先看执行性标记会把"我想自己弄懂"判反。
    """
    if any(mark in text or mark in low for mark in _NO_ANSWER_MARKS):
        return "instrumental"
    if any(mark in text or mark in low for mark in _EXECUTIVE_MARKS):
        return "executive"
    return "unclear"


# 短句里以"的 + 抽象名词"收尾的，多半是在**点名主题**而不是作答：
# "趋肤深度与频率的关系"、"麦克斯韦方程组的定义"。当成答案会让模型去"评判"一个主题词，
# 然后顺手把结论讲出来 —— 2026-09-26 真机截图里 引导档就是这么把公式直接给出去的。
# 只认"的 X"这种带定语的形式：否则"反比关系"（这是真的作答）会被一起误伤。
_TOPIC_TAIL_MARKS = (
    "的关系", "的定义", "的公式", "的概念", "的意思", "的原理", "的区别",
    "的推导", "的步骤", "的方法", "的作用", "的内容", "的结论", "的证明",
)


def _is_reply(text: str, low: str, seeking: str) -> bool:
    """这一轮不是提问，而是在回答 AI 上一轮的追问。

    判据朴素但稳：**短**、且没有任何"在提问"的标记。像"跑得快""因为损耗小"这种短语，
    在对话里几乎只可能是答案。把它当成"首次提问"会让本轮计划又指示模型去反问
    「你现在是怎么理解它的？」—— 于是它把上一轮原样再问一遍，用户看到的就是"没反应"。
    """
    if seeking != "unclear" or not text or len(text) > _REPLY_MAX:
        return False
    # 点名主题的短语不是作答 —— 见 _TOPIC_TAIL_MARKS 的说明。
    if any(mark in text for mark in _TOPIC_TAIL_MARKS):
        return False
    return not any(mark in text or mark in low for mark in _ASKING_MARKS)


def _signal(text: str, low: str, seeking: str) -> str:
    if any(mark in text or mark in low for mark in _PRACTICE_MARKS):
        return "practice"
    if seeking == "executive":
        return "demand"
    if any(mark in text or mark in low for mark in _STUCK_MARKS):
        return "stuck"
    if any(mark in text or mark in low for mark in _ATTEMPT_MARKS):
        return "attempt"
    if _is_reply(text, low, seeking):
        return "reply"
    return "first"


def _strip_frames(body: str) -> str:
    for _ in range(3):
        hit = next(
            (p for p in _FRAME_PREFIXES if body.startswith(p) and len(body) - len(p) >= 2),
            "",
        )
        if not hit:
            break
        body = body[len(hit) :]
    for tail in _FRAME_TAILS:
        if body.startswith(tail) and len(body) - len(tail) >= 2:
            body = body[len(tail) :]
            break
    for suffix in _FRAME_SUFFIXES:
        if body.endswith(suffix) and len(body) - len(suffix) >= 2:
            body = body[: -len(suffix)]
            break
    return body.strip()


def extract_topic(text: str) -> str:
    """从问句里抠出"问题焦点"，只用于给模型锚定，不当作事实结论。

    优先取引号里的原词（用户自己点名的术语最可靠）；否则按子句切分，丢掉
    纯疑问尾句（"为什么我错了"）和寒暄头（"你好"），剩下的剥掉提问外壳再截断。
    抠不出来就返回空串 —— 宁可不锚定，也不要给模型一个错的焦点。
    """
    raw = str(text or "").strip()
    if not raw:
        return ""
    for left, right in _QUOTE_PAIRS:
        start = raw.find(left)
        if start < 0:
            continue
        end = raw.find(right, start + 1)
        inner = raw[start + 1 : end].strip() if end > start else ""
        if 2 <= len(inner) <= 24:
            return inner
    parts = [p.strip() for p in re.split("[" + re.escape("".join(_CLAUSE_SPLIT)) + "]", raw)]
    parts = [p for p in parts if p]
    if len(parts) > 1 and len(parts[0]) <= 4 and parts[0].lower() in _GREETING_LEADS:
        parts.pop(0)
    while len(parts) > 1:
        tail = parts[-1]
        if len(_strip_frames(tail)) < 2 or (
            len(tail) <= 12 and any(tail.startswith(lead) for lead in _FRAME_LEADS)
        ):
            parts.pop()
            continue
        break
    body = _strip_frames(parts[0]) if parts else ""
    body = body.strip(" \t？?。！!，,、；;：:~")
    if len(body) < 2:
        return ""
    # 抠出来的是"我的状态/我的诉求"而不是主题，就干脆不锚定。
    if any(mark in body for mark in _STUCK_MARKS + _HELP_MARKS):
        return ""
    if body.startswith(_SELF_LEADS):
        return ""
    if len(body) > 20:
        head = body[:20]
        # 英文按词边界截断，免得把 "derive the wave equation" 切成 "derive the wave equ"
        body = head.rsplit(" ", 1)[0] if " " in head and head.isascii() else head
    return body


def classify_question(text: str) -> dict[str, str]:
    """把用户这一问拆成 类型 / 求助性质 / 卡壳信号 / 问题焦点 四项。"""
    raw = str(text or "").strip()
    low = raw.lower()
    kind = "meta" if _is_meta(raw, low) else "concept"
    if kind != "meta":
        for candidate, marks in _KIND_RULES:
            if any(mark in raw or mark in low for mark in marks):
                kind = candidate
                break
    seeking = _help_seeking(raw, low)
    signal = _signal(raw, low, seeking)
    return {
        "kind": kind,
        "help_seeking": seeking,
        "signal": signal,
        # 练习请求轮没有"问题焦点"可言（「练练」锚定进计划只会诱导模型围着这个词打转）。
        "topic": "" if signal == "practice" else extract_topic(raw),
    }


