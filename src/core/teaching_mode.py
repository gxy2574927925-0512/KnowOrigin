def tutor_role(mode: Any, task: str) -> str:
    """引导档要替换掉默认的「教材标准答案」人设；其余情况返回空串（不改既有行为）。"""
    if (task or "") not in _TUTOR_ROLE_TASKS:
        return ""
    if normalize_mode(mode) != "guided":
        return ""
    return _TUTOR_ROLE_BASE + _TUTOR_ROLE_FIELDS


def ladder_block(mode: Any, task: str, question: Any = None, weak: bool | None = None) -> str:
    """按档位、任务与**这一问**返回要追加到系统提示词后面的阶梯文本。

    ``direct`` 档、非教学任务一律返回空串 —— 也就是**完全不改变既有行为**。

    ``question`` 是用户这一轮的原话。给了它就返回**按问题定制的本轮计划**；
    给不出（老调用点、单测里直接调 ``_system_prompt``）则返回旧的固定口径 —— 
    旧文本一个字都没改，所以既有行为与既有断言都不受影响。
    ``weak`` 是该问题所锚定节点的掌握度是否偏低（可选），用来调提示的具体度。
    """
    normalized = normalize_mode(mode)
    if normalized == "direct" or (task or "") not in TUTOR_TASKS:
        return ""
    text = str(question if question is not None else active_question() or "").strip()
    if not text:
        return f"{_LADDER_CORE}\n{_MODE_RULES.get(normalized, '')}".strip()
    # 轮次摘要只在"真的要引导"时追加；闲聊/元问题那套块明确说了不要套阶梯，就不塞了。
    # 顺序：**摘要在前、本轮计划在后**。计划末尾的 _LADDER_CORE 是"别把提示词写进正文"
    # 的收口警告，放最后才压得住模型顺着摘要往下续写 —— 真机实测（2026-09-26 端到端流式）：
    # 摘要放在最后时，模型把「据此判断这是第几次尝试：用户第一次问这个点就停在 L0~L1…」
    # 那段内部指令原样吐进了回答，用户直接看到提示词。
    history = active_history()
    block = scaffold_block(
        normalized, text, weak=weak, stuck_repeat=_stuck_already(history)
    )
    if not history or block == _META_BLOCK:
        return block
    return f"{history}\n\n{block}"


