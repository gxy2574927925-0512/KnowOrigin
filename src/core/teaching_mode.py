    if not q or len(q) > 6:
        return False
    if q not in _ACCEPT_SHORT and q.lower() not in _ACCEPT_SHORT:
        return False
    ai_lines = [ln for ln in str(history or "").splitlines() if ln.startswith("AI：")]
    return bool(ai_lines) and any(m in ai_lines[-1] for m in _INVITE_MARKS)
