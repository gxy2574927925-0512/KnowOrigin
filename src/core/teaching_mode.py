# --------------------------------------------------------------------------
# 每用户偏好（仿 en_prefs）
# --------------------------------------------------------------------------


class TeachingPrefs:
    """极小的每用户偏好表：一个 owner 一行，一个 mode 字段。"""

    def __init__(self, path: str | Path):
        self.path = Path(path)
        if str(path) != ":memory:":
            self.path.parent.mkdir(parents=True, exist_ok=True)
        self._conn = sqlite3.connect(str(path), check_same_thread=False)
        self._conn.row_factory = sqlite3.Row
        self._conn.execute("PRAGMA foreign_keys = ON")
        self._conn.execute("PRAGMA busy_timeout = 5000")
        self.init_schema()

    @contextmanager
    def transaction(self) -> Iterator[sqlite3.Connection]:
        try:
            yield self._conn
            self._conn.commit()
        except Exception:
            self._conn.rollback()
            raise

    def init_schema(self) -> None:
        with self.transaction() as conn:
            conn.executescript(SCHEMA)

    def get(self, owner_id: str) -> str:
        row = self._conn.execute(
            "SELECT mode FROM teaching_prefs WHERE owner_id = ?", (owner_id or "",)
        ).fetchone()
        if row is None:
            return DEFAULT_MODE
        # 注意：不能写 `row["mode"] or DEFAULT_MODE` —— 与 en_prefs 的 new_per_day 同理，
        # 合法值的集合以后可能包含 falsy 项，显式判 None 才安全。
        raw = row["mode"]
        return normalize_mode(raw) if raw is not None else DEFAULT_MODE

    def set(self, owner_id: str, mode: Any) -> str:
        normalized = normalize_mode(mode)
        with self.transaction() as conn:
            conn.execute(
                "INSERT OR REPLACE INTO teaching_prefs (owner_id, mode, updated_at)"
                " VALUES (?, ?, ?)",
                (owner_id or "", normalized, _now()),
            )
        return normalized

    def close(self) -> None:
        self._conn.close()


