def probe(query: str) -> list[str]:
    """返回问题里**命中的口语主题词本身**（挂科 / 保研 / 宿舍 …）。

    这些词往往就是用户真正在问的主题，检索时值得当成强相关信号：
    标题里写着「挂科」的《挂科与试读》，比一篇正文碰巧撞上「补考 / 重修」的长文更贴题。
    """
    text = query or ""
    return [spoken for spoken in SYNONYMS if spoken and spoken in text]


def expand(query: str) -> list[str]:
    """把问题里的口语词扩展成官方措辞；按子串探测，命中即扩展。

    返回的是**可以直接拿去检索的官方词**（去重、保持词表登记顺序），
    调用方通常把它追加进检索词集合里，不覆盖原始查询。
    """
    text = query or ""
    out: list[str] = []
    for spoken, official in SYNONYMS.items():
        if spoken and spoken in text:
            for word in official:
                if word not in out:
                    out.append(word)
    return out


