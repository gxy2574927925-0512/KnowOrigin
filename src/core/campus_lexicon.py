# 带这些词的问题多半在问「怎么办」，值得把对口部门一并给出来
PROCEDURAL_HINTS: tuple[str, ...] = (
    # 明确的办事意图
    "怎么办", "怎么申请", "怎么办理", "怎样申请", "如何申请", "如何办理",
    "流程", "手续", "材料", "找谁", "去哪办", "在哪办", "能不能办", "需要什么",
    # 政策与条件类问法：答案写在规章里，我们资料里没有时同样要告诉用户「找谁」
    "条件", "要求", "规定", "政策", "标准", "资格", "要不要",
    # 动宾式的诉求：「我想换个宿舍」「想转专业」——同学往往不带「怎么办」，
    # 但这确实是在求办，不该因为少一个疑问词就把部门块丢掉。
    "想换", "想转", "想申请", "想办", "要办", "需要办",
    # 本身就是办事动词，出现即是在问流程
    "补办", "调宿", "换宿舍",
    # 故障描述：同学不说「怎么办」，只说「校园网连不上」「教务系统进不去」——
    # 这恰恰是最需要「找谁修」的一类，漏掉它等于把最急的问题答成「没查到」。
    "进不去", "连不上", "登不上", "打不开", "上不了", "用不了", "不能用",
    "报错", "坏了",
    # 丢失与挂失：丢了东西的第一反应是问怎么补，不是查规章
    "丢了", "不见了", "找不到了", "挂失",
    # 事前准备：问「要准备什么」其实是在问办事材料
    "准备",
)

# 「怎么 / 如何 / 怎样」后面直接跟动词的，几乎都在问办事（怎么签 / 怎么补办 / 怎么换…）。
# 逐个登记动词是打不完的地鼠——同学换个说法就漏。这里按结构识别，
# 只要疑问副词后面还有汉字就当作办事意图；「图书馆几点开门」这类没有疑问副词，
# 仍走事实查询路径，不会被误加部门块。
# 排除「怎么样」：那是在问评价（「食堂怎么样」），不是办事流程。
_PROCEDURAL_RE = re.compile(r"(怎么|如何|怎样|咋)(?!样)[\u4e00-\u9fff]")


def route(query: str, *, limit: int = 3) -> list[Desk]:
    """把问题路由到对口办事部门；无命中返回空列表。

    排序：命中关键词数优先，同分保持 DESKS 的登记顺序（即常见度）。

    匹配前先用同义词把口语扩成官方措辞：用户问「挂科了怎么办」，部门表里写的是
    「补考 / 重修」，不做这层扩展就一个字都对不上，教务处会被漏掉——而这正是
    用户最需要「找谁」的时刻。
    """
    text = query or ""
    haystack = text + " " + " ".join(expand(text))
    scored: list[tuple[float, int, Desk]] = []
    for idx, desk in enumerate(DESKS):
        hit = sum(1 for kw in desk.keywords if kw in haystack)
        if not hit:
            continue
        score = float(hit)
        if any(level in text and desk.name == owner for level, owner in _LEVEL_OWNER.items()):
            score += 1.5
        scored.append((score, idx, desk))
    scored.sort(key=lambda row: (-row[0], row[1]))
    return [row[2] for row in scored[: max(1, limit)]]


def wants_desk(query: str) -> bool:
    """问题是否在问办事流程（决定「对口部门」要不要一并给出，避免给常见问题添噪声）。"""
    text = query or ""
    if any(hint in text for hint in PROCEDURAL_HINTS):
        return True
    return bool(_PROCEDURAL_RE.search(text))


def routing_note(query: str, *, limit: int = 3) -> str:
    """生成给模型看的「找谁」提示；无对口部门时返回空串，不制造噪声。

    未登记官网的部门只给名称与职责，并明确提示去学校办公网查联系方式——
    编一个看起来合理的电话或邮箱，比不给更坏。
    """
    desks = route(query, limit=limit)
    if not desks:
        return ""
    lines = ["【办事对口部门·建议直接咨询】"]
    for desk in desks:
        where = f"　官网：{desk.site}" if desk.site else "（未登记官网，联系方式请以学校办公网为准）"
        lines.append(f"- {desk.name}：{desk.scope}。{where}")
    lines.append("以上为按问题主题匹配的对口部门，非官方答复；具体口径以学校办公网公布的最新信息为准。")
    return "\n".join(lines)